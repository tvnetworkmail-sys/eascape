import json,sys
P,D=sys.argv[1],sys.argv[2]
d=json.load(open(P+'/out.json'))
def cs(lv,x,z): return f"{lv}_{x//64}_{z//64}_{x%64}_{z%64}"
rows=[];seen=set()
for l in d['links']:
    k=(tuple(l['frm']),l['op'])
    if k in seen: continue
    seen.add(k)
    rows.append(f"[eascape_link_{len(rows)}]\ntable=eascape_links\ndata=from,{cs(*l['frm'])}\ndata=op,{l['op']}\ndata=to,{cs(*l['to'])}\ndata=up,{'true' if l['up'] else 'false'}\n")
hdr="// EASCape: where ladders, stairs, trapdoors and cave entrances lead, worked out from the 377 map\n// data (19 Oct 2026): each one's counterpart (the matching way back up or down) on the floor\n// above or below, or between the surface and underground (6400 squares north).\n// Generated by tools/world_links (docs/WORLD_LINKS.md).\n\n"
open(D+'/configs/eascape_links.dbrow','w').write(hdr+"\n".join(rows))
open(D+'/configs/eascape_links.dbtable','w').write("// EASCape: see eascape_links.dbrow\n[eascape_links]\ncolumn=from,coord,INDEXED,REQUIRED\ncolumn=op,int,REQUIRED\ncolumn=to,coord,REQUIRED\ncolumn=up,boolean,REQUIRED\n")
trig=[f"[oploc{o},{n}] ~eascape_door_walk;" for o,n in d['doors']]
done=set()
for l in d['links']:
    if l['h']: continue
    k=(l['op'],l['name'])
    if k in done: continue
    done.add(k); trig.append(f"[oploc{l['op']},{l['name']}] ~eascape_link({l['op']});")
src=open(P+'/head.rs2').read()
open(D+'/scripts/eascape_world.rs2','w').write(src+"\n// ---- generated\n\n"+"\n".join(trig)+"\n")
print(len(rows),len(trig))
