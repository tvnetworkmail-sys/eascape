import json,sys
P,D=sys.argv[1],sys.argv[2]
d=json.load(open(P+'/out.json'))
def cs(lv,x,z): return f"{lv}_{x//64}_{z//64}_{x%64}_{z%64}"
rows=[];seen=set()
import os
vpath=os.path.join(os.path.dirname(os.path.abspath(__file__)),'void_links.json')
void=json.load(open(vpath)) if os.path.exists(vpath) else []
# Void's teleports first: where Void says a ladder or staircase puts you, that wins
for v in void:
    k=(tuple(v['frm']),v['op'])
    if k in seen: continue
    seen.add(k)
    extra=f"data=kind,{v['kind']}\n"
    if v['kind']==1:
        to=v['frm']; extra+=f"data=dx,{v['dx']}\ndata=dz,{v['dz']}\ndata=dl,{v['dl']}\n"
    else:
        to=v['to']
        if v['kind']==3: extra+=f"data=w,{v['w']}\ndata=h,{v['h']}\n"
    up='true' if (v['kind']==1 and v.get('dl',0)>0) or (v['kind']!=1 and to[0]>v['frm'][0]) else 'false'
    rows.append(f"// Void: {v['void']} ({v['file']})\n[eascape_link_{len(rows)}]\ntable=eascape_links\ndata=from,{cs(*v['frm'])}\ndata=op,{v['op']}\ndata=to,{cs(*to)}\ndata=up,{up}\n{extra}")
for l in d['links']:
    k=(tuple(l['frm']),l['op'])
    if k in seen: continue
    seen.add(k)
    rows.append(f"[eascape_link_{len(rows)}]\ntable=eascape_links\ndata=from,{cs(*l['frm'])}\ndata=op,{l['op']}\ndata=to,{cs(*l['to'])}\ndata=up,{'true' if l['up'] else 'false'}\n")
hdr="// EASCape: where ladders, stairs, trapdoors and cave entrances lead, worked out from the 377 map\n// data (19 Oct 2026): each one's counterpart (the matching way back up or down) on the floor\n// above or below, or between the surface and underground (6400 squares north).\n// Generated by tools/world_links (docs/WORLD_LINKS.md).\n\n"
open(D+'/configs/eascape_links.dbrow','w').write(hdr+"\n".join(rows))
open(D+'/configs/eascape_links.dbtable','w').write("// EASCape: see eascape_links.dbrow\n[eascape_links]\ncolumn=from,coord,INDEXED,REQUIRED\ncolumn=op,int,REQUIRED\ncolumn=to,coord,REQUIRED\ncolumn=up,boolean,REQUIRED\n// 0 the matching counterpart (from the map); from Void: 1 move by dx/dz/dl, 2 exactly to, 3 the\n// nearest square of the w x h area at to\ncolumn=kind,int\ncolumn=dx,int\ncolumn=dz,int\ncolumn=dl,int\ncolumn=w,int\ncolumn=h,int\ndefault=kind,0\ndefault=dx,0\ndefault=dz,0\ndefault=dl,0\ndefault=w,1\ndefault=h,1\n")
trig=[f"[oploc{o},{n}] ~eascape_door_walk;" for o,n in d['doors']]
handled_names={}
for l in d['links']:
    if l['h']: handled_names.setdefault(l['op'],set()).add(l['name'])
# locs already scripted elsewhere (any trigger outside this file)
import re as _re
for dp,_,fs in os.walk(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','content','scripts')):
    for f in fs:
        if f.endswith('.rs2') and f!='eascape_world.rs2':
            for m in _re.finditer(r'^\[oploc(\d),([^\]_][^\]]*)\]',open(os.path.join(dp,f),errors='replace').read(),_re.M):
                handled_names.setdefault(int(m.group(1)),set()).add(m.group(2))
done=set()
for v in void:
    if (v['op'],v['name']) in done or v.get('h'): continue
    if v['name'] in handled_names.get(v['op'],set()): continue
    done.add((v['op'],v['name'])); trig.append(f"[oploc{v['op']},{v['name']}] ~eascape_link({v['op']});")
for l in d['links']:
    if l['h']: continue
    k=(l['op'],l['name'])
    if k in done: continue
    done.add(k); trig.append(f"[oploc{l['op']},{l['name']}] ~eascape_link({l['op']});")
src=open(P+'/head.rs2').read()
open(D+'/scripts/eascape_world.rs2','w').write(src+"\n// ---- generated\n\n"+"\n".join(trig)+"\n")
print(len(rows),len(trig))
