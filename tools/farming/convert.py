# Farming, step 1: the seed patches (allotments, flowers, herbs, hops). Builds, from Void's data
# (data/skill/farming), the state tables and crop rows our scripts read:
#   - farming_<type>_decode / _encode enums: the patch varbit's value <-> (crop, kind, stage),
#     packed as crop * 1000 + kind * 100 + stage; kinds 0 weeds, 1 growing, 2 watered, 3 diseased,
#     4 dead, 5 harvestable (Void's "lifeN": N harvests in)
#   - farming_crop rows: seed, produce, level, XP, seeds needed, harvest chance, disease chance
# The varbit values are the 377 cache's own (Void's 634 maps are the same patches: 700-783).
# Crops whose seed isn't in our cache (spirit weed, wergali...) are left out.
import re, sys, tomllib, glob, os
VOID = '/home/claude/greghib/void/data'
E = '/home/claude/eascape'
F = VOID + '/skill/farming'

ourobj = {}
for line in open(E + '/content/pack/obj.pack'):
    a, b = line.strip().split('=', 1); ourobj[int(a)] = b
ORIG_OBJ = 7957

voidid = {}
for f in glob.glob(VOID + '/**/*.items.toml', recursive=True):
    txt = open(f, encoding='utf-8', errors='replace').read()
    for m in re.finditer(r'^\[([\w.]+)\]\s*\n(?:(?!\[)[^\n]*\n)*?id = (\d+)', txt, re.M):
        voidid.setdefault(m.group(1), int(m.group(2)))
def our(name):
    i = voidid.get(name)
    if i is None or i >= ORIG_OBJ or i not in ourobj:
        return None
    return ourobj[i]

# item params anywhere in Void's data (farming_xp, farming_chance on produce)
itemparams = {}
for f in glob.glob(VOID + '/**/*.items.toml', recursive=True):
    try:
        d = tomllib.load(open(f, 'rb'))
    except Exception:
        continue
    for k, v in d.items():
        if isinstance(v, dict):
            itemparams.setdefault(k, v)

seeds = tomllib.load(open(F + '/seed.items.toml', 'rb'))
seedfile = set(seeds)
seeds.update({k: v for k, v in itemparams.items() if 'farming_crop' in v and k not in seeds})
disease = {k: v.get('disease_chance', 0) for k, v in tomllib.load(open(F + '/farming_produce.toml', 'rb')).items()}

# varbit value maps (regex: Void's file has a duplicate key tomllib refuses)
vmaps = {}
txt = open(F + '/farming.varbits.toml').read()
for m in re.finditer(r'^\[(\w+)\]\s*\nid = (\d+)[\s\S]*?values = \{([^}]*)\}', txt, re.M):
    pairs = re.findall(r'(\w+)\s*=\s*(\d+)', m.group(3))
    vmaps[m.group(1)] = (int(m.group(2)), pairs)

TYPES = [  # (our type id, name, void patch type, a Void varbit of that type, harvest param file)
    (1, 'allotment', 'allotment', 'farming_veg_patch_falador_nw', 'allotment_patch'),
    (2, 'flower', 'flower', 'farming_flower_patch_falador', 'flower_patch'),
    (3, 'herb', 'herb', 'farming_herb_patch_falador', 'herb_patch'),
    (4, 'hops', 'hops', 'farming_hops_patch_lumbridge', 'hop_patch'),
    # step 2a: trees and fruit trees (kinds 6 check-health, 7 stump; a fruit tree's lifeN is N fruit)
    (5, 'tree', 'tree', 'farming_tree_patch_lumbridge', 'tree_patch'),
    (6, 'fruit_tree', 'fruit_tree', 'farming_fruit_tree_patch_catherby', 'fruit_tree_patch'),
]
KIND = {'grow': 1, 'watered': 2, 'diseased': 3, 'dead': 4, 'life': 5}
# trees: what they give (logs are woodcutting's; fruit trees their fruit), Void's names
TREE_PRODUCE = {'oak': 'oak_logs', 'willow': 'willow_logs', 'maple': 'maple_logs', 'yew': 'yew_logs', 'magic': 'magic_logs',
                'apple': 'cooking_apple', 'banana': 'banana', 'orange': 'orange', 'curry': 'curry_leaf',
                'pineapple': 'pineapple', 'papaya': 'papaya_fruit', 'palm': 'coconut'}
claimxp = {}
for objfile in ('tree_patch', 'fruit_tree_patch'):
    for k, v in tomllib.load(open(F + f'/patch/{objfile}.objs.toml', 'rb')).items():
        if not isinstance(v, dict) or 'farming_xp' not in v: continue
        m = re.match(r'^(\w+?)_tree_(claim_xp|fullygrown_1)$', k)
        if m: claimxp[m.group(1)] = round(float(v['farming_xp']) * 10)

crops = []      # dicts
cropidx = {}    # crop name -> index
def crop_index(name):
    if name not in cropidx:
        cropidx[name] = len(cropidx) + 1
    return cropidx[name]
HERB_DEAD = 99

out_enum = ['// EASCape: Farming patch states, generated by tools/farming/convert.py from Void\'s',
            '// farming.varbits.toml. Packed state: crop * 1000 + kind * 100 + stage (kinds: 0 weeds,',
            '// 1 growing, 2 watered, 3 diseased, 4 dead, 5 harvestable). -1: not a state we know.', '']
harvest = {}
for tid, tname, vtype, vb, objfile in TYPES:
    objs = tomllib.load(open(F + f'/patch/{objfile}.objs.toml', 'rb'))
    for k, v in objs.items():
        if isinstance(v, dict) and 'harvest' in v and k.endswith('_fullygrown') and k[:-len('_fullygrown')] not in harvest:
            harvest[k[:-len('_fullygrown')]] = v['harvest']
    # crops of this type that we have seeds for
    okcrops = {}
    for sname, s in seeds.items():
        if s.get('farming_patch') != vtype:
            continue
        seed = our(sname)
        if seed is None:
            continue
        if s['farming_crop'] in okcrops and sname not in seedfile:
            continue
        okcrops[s['farming_crop']] = (sname, s)
    dec, enc = {}, {}
    vid, pairs = vmaps[vb]
    for name, val in pairs:
        val = int(val)
        m = re.match(r'^weeds_(life)?(\d)$', name)
        if m:
            st = int(m.group(2))
            if st > 3: continue
            key = st
            dec.setdefault(val, key)
            if m.group(1) is None or key not in enc or tid == 1 and st == 3:
                if not (m.group(1) and key in enc and tid != 1):
                    enc[key] = val if (m.group(1) is None or key not in enc) else enc[key]
            continue
        if name.startswith('herb_dead_'):
            key = HERB_DEAD * 1000 + 4 * 100 + int(name.rsplit('_', 1)[1])
            dec.setdefault(val, key); enc.setdefault(key, val); continue
        m = re.match(r'^(\w+?)_(claim|stump)$', name)
        if m and tid >= 5:
            if m.group(1) not in okcrops: continue
            key = crop_index(m.group(1)) * 1000 + (6 if m.group(2) == 'claim' else 7) * 100
            dec.setdefault(val, key); enc.setdefault(key, val); continue
        m = re.match(r'^(\w+?)_(watered_|diseased_|dead_)?(life)?(\d+)$', name)
        if not m:
            continue
        crop, kindp, life, st = m.group(1), m.group(2), m.group(3), int(m.group(4))
        if crop not in okcrops:
            continue
        kind = 5 if life else KIND[kindp[:-1]] if kindp else 1
        key = crop_index(crop) * 1000 + kind * 100 + st
        dec.setdefault(val, key); enc.setdefault(key, val)
    # the overgrown allotment shows as weeds_life3 (value 0)
    if tid == 1:
        enc[3] = 0
    for crop, (sname, s) in okcrops.items():
        if crop_index(crop) and not any(k // 1000 == cropidx[crop] for k in enc):
            continue
        prod = harvest.get(crop) or harvest.get(crop + '_hops')
        if tid >= 5:
            prod = TREE_PRODUCE.get(crop)
        if tid == 3:
            prod = 'grimy_' + crop
        if crop == 'barley':
            prod = 'barley'  # Void has barley_malt; the wiki: harvesting gives barley
        p = itemparams.get(prod if crop != 'barley' else 'barley_malt', {}) if prod else {}
        ch = p.get('farming_chance', '0-0').split('-')
        stages = max(k % 100 for k in enc if k // 1000 == cropidx[crop] and (k // 100) % 10 == 1)
        dkey = crop + ('_plant' if crop == 'pineapple' else '_tree') if tid >= 5 else crop
        crops.append(dict(checkxp=claimxp.get(crop, 0), idx=cropidx[crop], crop=crop, type=tid, seed=our(sname), produce=our(prod) if prod else None,
                          level=s.get('farming_level', 1), xp=round(float(s.get('farming_xp', 0)) * 10),
                          amount=s.get('farming_amount', 1), hxp=round(float(p.get('farming_xp', 0)) * 10),
                          clow=int(ch[0]), chigh=int(ch[1]), disease=disease.get(dkey, 0), stages=stages,
                          name=crop.replace('_', ' ')))
    out_enum += [f'[farming_{tname}_decode]', 'inputtype=int', 'outputtype=int', 'default=-1']
    out_enum += [f'val={k},{v}' for k, v in sorted(dec.items())] + ['']
    out_enum += [f'[farming_{tname}_encode]', 'inputtype=int', 'outputtype=int', 'default=-1']
    out_enum += [f'val={k},{v}' for k, v in sorted(enc.items())] + ['']

cfg = E + '/content/scripts/skill_farming/configs'
open(cfg + '/farming_states.enum', 'w').write('\n'.join(out_enum))
tbl = ['// EASCape: Farming crops (tools/farming/convert.py, from Void\'s seed, produce and patch data).',
       '[farming_crop]',
       'column=index,int,INDEXED,REQUIRED', 'column=seed,obj,INDEXED,REQUIRED', 'column=produce,namedobj',
       'column=name,string,REQUIRED', 'column=patchtype,int,REQUIRED', 'column=level,int,REQUIRED',
       'column=plantxp,int,REQUIRED', 'column=harvestxp,int,REQUIRED', 'column=seeds,int,REQUIRED',
       'column=chance,int,int,REQUIRED', 'column=disease,int,REQUIRED', 'column=stages,int,REQUIRED',
       '// trees and fruit trees: the check-health experience (tenths)', 'column=checkxp,int', '']
open(cfg + '/farming_crops.dbtable', 'w').write('\n'.join(tbl))
rows = ['// EASCape: Farming crops (tools/farming/convert.py). XP in tenths. chance: Void\'s',
        '// farming_chance (a harvest keeps the patch going, out of 256 from level 1 to 99).', '']
for c in sorted(crops, key=lambda c: c['idx']):
    rows += [f"[farming_crop_{c['crop']}]", 'table=farming_crop', f"data=index,{c['idx']}", f"data=seed,{c['seed']}"]
    if c['produce']: rows.append(f"data=produce,{c['produce']}")
    rows += [f"data=name,{c['name']}", f"data=patchtype,{c['type']}", f"data=level,{c['level']}",
             f"data=plantxp,{c['xp']}", f"data=harvestxp,{c['hxp']}", f"data=seeds,{c['amount']}",
             f"data=chance,{c['clow']},{c['chigh']}", f"data=disease,{c['disease']}", f"data=stages,{c['stages']}"]
    if c['checkxp']: rows.append(f"data=checkxp,{c['checkxp']}")
    rows.append('')
open(cfg + '/farming_crops.dbrow', 'w').write('\n'.join(rows))
for c in sorted(crops, key=lambda c: c['idx']):
    print(c['idx'], c['type'], c['crop'], c['seed'], c['produce'], c['level'], c['xp'], c['hxp'], c['amount'], c['clow'], c['chigh'], c['disease'], c['stages'])
const = ['// EASCape: Farming crop indexes (tools/farming/convert.py)']
const += [f"^farming_crop_{c['crop']} = {c['idx']}" for c in sorted(crops, key=lambda c: c['idx'])]
const += [f'^farming_crop_herb_dead = {HERB_DEAD}']
open(cfg + '/farming_crops.constant', 'w').write('\n'.join(const) + '\n')
