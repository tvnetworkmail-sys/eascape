P = []
for i in range(8): P.append((len(P) + 1, f'farming_veg_patch_{i + 1}', 708 + i, 1))
for i in range(4): P.append((len(P) + 1, f'farming_flower_patch_{i + 1}', 728 + i, 2))
for i in range(4): P.append((len(P) + 1, f'farming_herb_patch_{i + 1}', 780 + i, 3))
for i in range(4): P.append((len(P) + 1, f'farming_hops_patch_{i + 1}', 716 + i, 4))
# step 2a: tree patches 21-24 (Taverley, Falador, Varrock, Lumbridge), fruit tree patches 25-28
# (Gnome Stronghold, Tree Gnome Village, Brimhaven, Catherby)
for i in range(4): P.append((len(P) + 1, f'farming_tree_patch_{i + 1}', 700 + i, 5))
for i in range(4): P.append((len(P) + 1, f'farming_fruit_tree_patch_{i + 1}', 704 + i, 6))
o = ["// EASCape: Farming's patches, generated by tools/farming/patches.py. Index, the patch loc, its",
     "// varbit (the 377 cache's farming varbits, the same numbers as Void's) and type (1 allotment,",
     "// 2 flower, 3 herb, 4 hops, 5 tree, 6 fruit tree). Allotments 1-8 pair with flower patch 9 + (n - 1) / 2.", '',
     '[proc,farming_patch_count]()(int)', f'return({len(P)});', '',
     '[proc,farming_patch_get](int $patch)(int)', 'switch_int ($patch) {']
o += [f'    case {i} : return(%varbit_{v});' for i, n, v, t in P]
o += ['}', 'return(-1);', '', '[proc,farming_patch_set](int $patch, int $value)', 'switch_int ($patch) {']
o += [f'    case {i} : %varbit_{v} = $value;' for i, n, v, t in P]
o += ['}', '', '[proc,farming_patch_type](int $patch)(int)',
      'if ($patch <= 8) return(1);', 'if ($patch <= 12) return(2);', 'if ($patch <= 16) return(3);', 'if ($patch <= 20) return(4);', 'if ($patch <= 24) return(5);', 'return(6);', '']
for i, n, v, t in P:
    o += [f'[oploc1,{n}] ~farming_op1({i});', f'[oploc2,{n}] ~farming_inspect({i});',
          f'[oploc4,{n}] ~farming_guide;', f'[oplocu,{n}] ~farming_use({i});']
open('content/scripts/skill_farming/scripts/farming_patches.rs2', 'w').write('\n'.join(o) + '\n')
