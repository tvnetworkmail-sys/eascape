# Forgettable Tale...: the three cart puzzles' track maps and screen buttons, read off the cache's
# puzzle interfaces (inter_179, inter_180, inter_288: the 2007 cache's 128-130). Each junction has
# two models, one lit when it holds a green stone (1) and one when it holds a yellow (2); a model's
# leftmost and rightmost vertices are where that way starts and ends, on a grid of 96 units
# (offset 48 across on inter_179). A way that ends on another junction leads there; the other ends
# are the boxes, the top box, the exit or dead ends, as the OSRS wiki's solution pictures show them
# (Forgettable Tale - cart 1-1 .. 3-3). The "Set Junction" buttons are in junction order; the stone
# layer of junction j is com_(first + 2(j - 1)).
# Writes content/scripts/quests/quest_forgettable_tale/scripts/ft_tracks.rs2 and ft_puzzle_ui.rs2.
# Usage: tracks.py   (run with python3 -I from anywhere)
import os, re, struct
E = os.path.abspath(os.path.dirname(os.path.abspath(__file__)) + '/../..')
IF = E + '/content/scripts/interfaces/'
MODELS = E + '/content/models/com/'
OUT = E + '/content/scripts/quests/quest_forgettable_tale/scripts/'

def vertices(path):
    # x and z of a 377 model's vertices (the vertex part of the ob2 format)
    d = open(path, 'rb').read(); f = d[-18:]
    vc, fc = struct.unpack('>HH', f[0:4]); tfc = f[4]; has_info = f[5]; prio = f[6]; has_alpha = f[7]
    has_fl = f[8]; has_vl = f[9]
    lx, ly, lz, lf = struct.unpack('>HHHH', f[10:18])
    pos = vc + fc
    if prio == 255: pos += fc
    if has_fl: pos += fc
    if has_info: pos += fc
    if has_vl: pos += vc
    if has_alpha: pos += fc
    pos += lf + fc * 2 + tfc * 6
    xo = pos; yo = xo + lx; zo = yo + ly
    def smart(o):
        v = d[o]
        if v < 128: return v - 64, o + 1
        return ((v << 8) | d[o + 1]) - 49152, o + 2
    x = y = z = 0; pts = []
    for i in range(vc):
        fl = d[i]
        if fl & 1: dx, xo = smart(xo); x += dx
        if fl & 2: dy, yo = smart(yo); y += dy
        if fl & 4: dz, zo = smart(zo); z += dz
        pts.append((x, z))
    return pts

def components(name):
    txt = open(IF + name + '.if').read()
    return re.findall(r'\[(com_\d+)\]\n(.*?)(?=\n\[|\Z)', txt, re.S)

def snap(v, o): return o + round((v - o) / 96) * 96

ROOMS = {1: ('inter_179', 48), 2: ('inter_180', 0), 3: ('inter_288', 0)}
EXIT, BOX1, BOX2, TOP, DEAD = '^ft_exit', '^ft_box1', '^ft_box2', '^ft_top', '^ft_dead'
ENDS = {1: {(-48, 0): BOX1, (144, 96): BOX2, (144, 288): TOP, (144, -96): EXIT},
        2: {(0, 0): BOX1, (192, -96): BOX2, (192, 192): TOP, (288, 0): EXIT},
        3: {(0, 96): BOX1, (192, 0): BOX2, (384, 96): EXIT}}
tracks = {}; buttons = {}; layers = {}; closes = {}
for r, (name, ox) in ROOMS.items():
    J = {}
    comps = components(name)
    for com, body in comps:
        vb = re.search(r'push_varbit,forget_if(\d+)', body); eq = re.search(r'script1=eq,(\d)', body)
        mo = re.search(r'^model=(\S+)', body, re.M)
        if vb and eq and mo and not re.search(r'^layer=', body, re.M):
            J.setdefault(int(vb.group(1)), {})[int(eq.group(1))] = mo.group(1)
        if vb and re.search(r'^layer=(com_\d+)', body, re.M):
            layers.setdefault(r, {})[int(vb.group(1))] = re.search(r'^layer=(com_\d+)', body, re.M).group(1)
        if 'option=Set Junction' in body: buttons.setdefault(r, []).append(com)
        if 'option=Close' in body or (r == 2 and 'text=Close' in body): closes[r] = com
    tracks[r] = {}
    for j in sorted(J):
        ways = []
        for v in (1, 2):
            pts = vertices(MODELS + J[j][v] + '.ob2')
            lo = min(p[0] for p in pts); hi = max(p[0] for p in pts)
            zl = [p[1] for p in pts if p[0] == lo]; zr = [p[1] for p in pts if p[0] == hi]
            ways.append(((snap(lo - 18, ox), snap(sum(zl) / len(zl), 0)), (snap(hi + 18, ox), snap(sum(zr) / len(zr), 0))))
        tracks[r][j] = (ways[0][0], ways[0][1], ways[1][1])

L = ["// EASCape: generated by tools/forgettable_tale/tracks.py from the cache's puzzle interfaces",
     "// (inter_179, inter_180, inter_288: each junction's green and yellow ways are its own models, whose",
     "// ends give where each way goes). The boxes, the exit and the dead ends are the OSRS wiki's",
     "// solution pictures. A target is a junction (1-19), ^ft_exit, ^ft_box1, ^ft_box2, ^ft_top or",
     "// ^ft_dead; x and z are in the track map's units (96 between junctions).", "",
     "[proc,ft_jnode](int $room, int $j)(int, int)", "switch_int (calc($room * 100 + $j)) {"]
for r in tracks:
    for j, (s, g, y) in sorted(tracks[r].items()):
        L.append(f'    case {r * 100 + j} : return({s[0]}, {s[1]});')
L += ['}', 'return(0, 0);', '', '[proc,ft_edge](int $room, int $j, int $dir)(int, int, int)',
      'switch_int (calc($room * 1000 + $j * 10 + $dir)) {']
for r in tracks:
    at = {v[0]: j for j, v in tracks[r].items()}
    for j, (s, g, y) in sorted(tracks[r].items()):
        for d, t in ((1, g), (2, y)):
            tgt = str(at[t]) if t in at else ENDS[r].get(t, DEAD)
            L.append(f'    case {r * 1000 + j * 10 + d} : return({tgt}, {t[0]}, {t[1]});')
L += ['}', 'return(^ft_dead, 0, 0);']
open(OUT + 'ft_tracks.rs2', 'w').write('\n'.join(L) + '\n')

U = ["// EASCape: the three cart puzzle screens (the cache's inter_179, inter_180 and inter_288): their",
     "// \"Set Junction\" buttons, in junction order, and the layer that shows each junction's stone.",
     "// Generated by tools/forgettable_tale/tracks.py.", ""]
for r, (name, ox) in ROOMS.items():
    for j, com in enumerate(buttons[r], 1):
        U.append(f'[if_button,{name}:{com}] ~ft_junction_click({r}, {j});')
    U.append(f'[if_button,{name}:{closes[r]}] if_close;')
    U.append('')
U += ['[proc,ft_stone_layer](int $room, int $j)(component)', 'switch_int (calc($room * 100 + $j)) {']
for r, (name, ox) in ROOMS.items():
    for j in sorted(layers[r]):
        U.append(f'    case {r * 100 + j} : return({name}:{layers[r][j]});')
U += ['}', 'return(null);', '', '[proc,ft_junction](int $j)(int)', 'switch_int ($j) {']
U += [f'    case {j} : return(%forget_if{j});' for j in range(1, 20)]
U += ['}', 'return(0);', '', '[proc,ft_junction_set](int $j, int $v)', 'switch_int ($j) {']
U += [f'    case {j} : %forget_if{j} = $v;' for j in range(1, 20)]
U += ['}']
open(OUT + 'ft_puzzle_ui.rs2', 'w').write('\n'.join(U) + '\n')
print({r: len(tracks[r]) for r in tracks})
