#!/usr/bin/env python3
# 2006RS-2: writes app2/src/plugins/loottracker/cluetiers2006.js, the tier of every clue item our game has
# (scrolls, puzzle boxes, challenge scrolls, caskets: content/pack/obj.pack's trail_clue_<tier>_*, certs left out).
# Our server says "Well done you've completed the Treasure Trail!" with no tier (trail_clue_helper.rs2
# trail_complete), so the Loot Tracker names the reward by the last clue item it saw in the pack.
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
PACK = os.path.join(ROOT, 'content', 'pack', 'obj.pack')
OUT = os.path.join(ROOT, 'app2', 'src', 'plugins', 'loottracker', 'cluetiers2006.js')

tiers = {'easy': [], 'medium': [], 'hard': []}
with open(PACK, encoding='utf-8') as f:
    for line in f:
        m = re.match(r'^(\d+)=trail_clue_(easy|medium|hard)_', line.strip())
        if m:
            tiers[m.group(2)].append(int(m.group(1)))


def ranges(ids):
    out = []
    for i in sorted(ids):
        if out and out[-1][1] == i - 1:
            out[-1][1] = i
        else:
            out.append([i, i])
    return out


body = ','.join('"%s":%s' % (t, str(ranges(v)).replace(' ', '')) for t, v in tiers.items())
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by app2/tools/runelite/cluetiers2006.py from content/pack/obj.pack: each clue tier\'s item ids as\n')
    f.write('// [first, last] ranges (scrolls, puzzle boxes, challenge scrolls, caskets). Do not edit.\n')
    f.write('(() => {\n  const ll = window.__lostlite;\n  if (ll) ll.clueTiers2006 = {%s};\n})();\n' % body)
print('wrote', OUT, {t: len(v) for t, v in tiers.items()})
