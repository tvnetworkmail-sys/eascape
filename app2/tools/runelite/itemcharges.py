"""RuneLite's Item Charges ItemWithCharge / ItemWithConfig enums trimmed to the 2007 cache.

    RUNELITE_SRC=<RuneLite source root> python3 itemcharges.py <client_items.json>

writes app/src/plugins/itemcharges/data.js: withCharge [NAME, ItemChargeType, id, charges] and withConfig
[NAME, id, configKey, ItemChargeType] for each constant whose item the running client has (client_items.json, a dump
of the client's item names: {id: name}; the client's item ids are OSRS's). Items after Sept 2007 aren't in the cache.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gameval  # noqa: E402

OUT = os.path.join(gameval.REPO, 'app/src/plugins/itemcharges/data.js')
D = 'runelite-client/src/main/java/net/runelite/client/plugins/itemcharges/'
NAMES = {}
# from 11678 up the 2007 cache's items are its own (God Wars, Varrock armour, ...: OSRS gave them new ids and reused
# these for later items such as Nightmare Zone's potions), so an OSRS id there isn't the same item
OSRS_RENUMBERED = 11678
KEYS = {}


def item(a):
    m = re.match(r'ItemID\.(\w+)', a.strip())
    i = m and gameval.gameval('ItemID').get(m.group(1))
    return i if i is not None and str(i) in NAMES and i < OSRS_RENUMBERED else None


def main():
    cfg = open(os.path.join(gameval.RL, D + 'ItemChargeConfig.java')).read()
    for k, v in re.findall(r'String (KEY_\w+) = "(\w+)"', cfg):
        KEYS[k] = v
    wc, dropped = [], []
    for name, args, _ in gameval.enum_entries(open(os.path.join(gameval.RL, D + 'ItemWithCharge.java')).read(), 'ItemWithCharge'):
        i = item(args[1])
        if i is None:
            dropped.append(name)
            continue
        wc.append([name, args[0].split('.')[-1], i, int(args[2])])
    wf = []
    for name, args, _ in gameval.enum_entries(open(os.path.join(gameval.RL, D + 'ItemWithConfig.java')).read(), 'ItemWithConfig'):
        i = item(args[0])
        if i is None:
            dropped.append(name)
            continue
        wf.append([name, i, KEYS[args[1].split('.')[-1]], args[2].split('.')[-1]])
    js = ('// Generated by app/tools/runelite/itemcharges.py: RuneLite\'s ItemWithCharge [NAME, type, id, charges] and\n'
          '// ItemWithConfig [NAME, id, configKey, type] trimmed to the items in the 2007 cache.\n'
          'window.__lostlite && (window.__lostlite.itemChargesData = ' +
          json.dumps({'withCharge': wc, 'withConfig': wf}, separators=(',', ':')) + ');\n')
    open(OUT, 'w').write(js)
    print(len(wc), '+', len(wf), 'kept,', len(dropped), 'dropped:', ' '.join(dropped))
    print('types:', sorted(set(r[1] for r in wc) | set(r[3] for r in wf)))


if __name__ == '__main__':
    NAMES.update(json.load(open(sys.argv[1])))
    main()
