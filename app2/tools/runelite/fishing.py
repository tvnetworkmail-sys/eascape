"""RuneLite's net.runelite.client.game.FishingSpot trimmed to the 2007 cache.

    RUNELITE_SRC=<RuneLite checkout> python3 fishing.py

writes app/src/plugins/runelite/fishingspot.js (rl.FishingSpot). OSRS renumbered the fishing spot NPCs, but their
Jagex names (e.g. _0_43_51_SALTFISH) are the 2007 cache's debug names, so each resolves by name (gameval.resolve);
a spot with no 2007 NPC (anglerfish, minnows, aerial, Tempoross, ...) or whose fish isn't in the 2007 cache is left out.
"""
import json
import os
import sys

import gameval as gv

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.normpath(os.path.join(HERE, '..', '..'))


def main():
    src = open(os.path.join(gv.RL, 'runelite-client/src/main/java/net/runelite/client/game/FishingSpot.java')).read()
    spots, dropped = [], []
    for name, args, _ in gv.enum_entries(src, 'FishingSpot'):
        tooltip = json.loads(args[1]) if args[1].startswith('"') else None
        rest = args[2:] if tooltip is not None else args[1:]
        item = gv.resolve('ItemID', rest[0].split('.', 1)[1])
        ids = [gv.resolve('NpcID', r.split('.', 1)[1]) for r in rest[1:] if r.startswith('NpcID.')]
        ids = [i for i in ids if i is not None]
        if item is None or not ids:
            dropped.append(name)
            continue
        spots.append({'name': name, 'spot': json.loads(args[0]), 'worldMapTooltip': tooltip or json.loads(args[0]), 'fishSpriteId': item, 'ids': ids})
    with open(os.path.join(APP, 'src/plugins/runelite/fishingspot.js'), 'w') as f:
        f.write("// Generated by app/tools/runelite/fishing.py: RuneLite's net.runelite.client.game.FishingSpot, trimmed to the spots\n")
        f.write("// whose NPCs and fish are in the 2007 cache (rl.FishingSpot: values(), findSpot(id), getName, getWorldMapTooltip,\n")
        f.write("// getFishSpriteId, getIds). Left out: " + ', '.join(dropped) + '.\n')
        f.write('(() => {\n  const ll = window.__lostlite;\n  const rl = ll && ll.rl;\n  if (!rl) return;\n')
        f.write('  const DATA = ' + json.dumps(spots, separators=(',', ':')) + ';\n')
        f.write('''  class FishingSpot {
    constructor(d) { this.key = d.name; this.name = d.spot; this.worldMapTooltip = d.worldMapTooltip; this.fishSpriteId = d.fishSpriteId; this.ids = d.ids; }
    getName() { return this.name; }
    getWorldMapTooltip() { return this.worldMapTooltip; }
    getFishSpriteId() { return this.fishSpriteId; }
    getIds() { return this.ids; }
    toString() { return this.key; }
  }
  const VALUES = DATA.map((d) => new FishingSpot(d));
  const SPOTS = new Map();
  for (const spot of VALUES) { FishingSpot[spot.key] = spot; for (const id of spot.ids) if (!SPOTS.has(id)) SPOTS.set(id, spot); }
  FishingSpot.values = () => VALUES;
  FishingSpot.findSpot = (id) => SPOTS.get(id) || null;
  rl.FishingSpot = FishingSpot;
})();
''')
    print('spots', [s['name'] + ':' + str(len(s['ids'])) for s in spots], 'dropped', dropped, file=sys.stderr)


if __name__ == '__main__':
    main()
