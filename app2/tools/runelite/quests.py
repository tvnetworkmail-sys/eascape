"""The 2007 quest list as RuneLite's Quest / QuestState (Diary Requirements' QuestRequirement, and later clones).

    python3 quests.py [path/to/runelite-api/.../Quest.java]

writes app/src/plugins/runelite/quest.js (rl.Quest, rl.QuestState, rl.VarPlayerID.QP). OSRS's Quest.getState runs
QUEST_STATUS_GET; the 2007 quest list (interface 274) has no such script: the server colours each quest's line
(~send_quest_progress_colour: red not started, yellow started, green finished), so getState reads that colour. Each
quest's line is the server's questlist.if component (its text the quest's name) at the 2007 component Com2007 maps it
to. The enum names are RuneLite's (the name in upper snake case, or RENAMED where RuneLite's name differs); given
RuneLite's Quest.java, every enum name is checked against it.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
QUESTLIST = os.path.join(REPO, 'content/scripts/interfaces/questlist.if')
TABLE = os.path.join(REPO, 'engine/src/network/game/server/codec/Com2007Table.ts')
HAND = os.path.join(REPO, 'engine/src/network/game/server/codec/Com2007.ts')
OUT = os.path.join(REPO, 'app/src/plugins/runelite/quest.js')

# our quest list's names RuneLite spells differently (OSRS renamed or numbered these later): questlist key -> enum
RENAMED = {
    'doric': 'DORICS_QUEST', 'romeojuliet': 'ROMEO__JULIET', 'vampire': 'VAMPYRE_SLAYER', 'itexam': 'THE_DIG_SITE',
    'elemental_workshop': 'ELEMENTAL_WORKSHOP_I', 'fairy_farmers': 'FAIRYTALE_I__GROWING_PAINS',
    'fairy2': 'FAIRYTALE_II__CURE_A_QUEEN', 'waterfall': 'WATERFALL_QUEST', 'hero': 'HEROES_QUEST',
    'mm': 'MONKEY_MADNESS_I', 'mourning': 'MOURNINGS_END_PART_I', 'mourning2': 'MOURNINGS_END_PART_II',
    'itgronigen': 'OBSERVATORY_QUEST', 'ratcatch': 'RATCATCHERS', 'itwatchtower': 'WATCHTOWER', 'dragon': 'DRAGON_SLAYER_I',
    'deserttreasure': 'DESERT_TREASURE_I', 'rag': 'RAG_AND_BONE_MAN_I',
}


def enum_name(name):
    return re.sub(r'_+', '_', re.sub(r'[^A-Z0-9]', '_', name.upper().replace("'", '').replace('&', 'AND'))).strip('_')


def main():
    text = {}
    key = None
    for line in open(QUESTLIST):
        m = re.match(r'^\[(\w+)\]', line)
        if m:
            key = m.group(1)
        elif key and line.startswith('text='):
            text[key] = line[5:].strip()
    com = {}
    for k, c in re.findall(r'"questlist:(\w+)": \[274, (\d+)\]', open(TABLE).read()):
        com[k] = int(c)
    for k, c in re.findall(r"'questlist:(\w+)': com\(274, (\d+)\)", open(HAND).read()):
        com[k] = int(c)
    rl_names = None
    if len(sys.argv) > 1:
        rl_names = dict((n, d) for n, d in re.findall(r'^\t([A-Z0-9_]+)\(\d+, "([^"]+)"', open(sys.argv[1]).read(), re.M))
    quests = {}
    for k, c in sorted(com.items(), key=lambda kv: kv[1]):
        name = text.get(k)
        if not name or name.endswith(':') or name.startswith('Quest Points') or k.startswith('com_'):
            continue
        e = RENAMED.get(k) or enum_name(re.sub(r' Quest$', '', name))
        if e not in RENAMED.values() and rl_names is not None and e not in rl_names and enum_name(name) in rl_names:
            e = enum_name(name)
        if rl_names is not None and e not in rl_names:
            print('not in RuneLite:', k, name, e)
            continue
        if rl_names is not None:
            name = rl_names[e]
        quests[e] = [name, c]
    js = """// Generated by app/tools/runelite/quests.py: the 2007 quest list as RuneLite's Quest / QuestState (rl.Quest,
// rl.QuestState, rl.VarPlayerID.QP). OSRS's Quest.getState runs QUEST_STATUS_GET; 2007 has no such script: the server
// colours each quest's line in the quest list (interface 274: red not started, yellow started, green finished), so
// getState reads that colour (read only).
(() => {
  const ll = window.__lostlite;
  const rl = ll && ll.rl;
  if (!rl) return;
  const QUESTS = %s;
  const QuestState = { NOT_STARTED: 'NOT_STARTED', IN_PROGRESS: 'IN_PROGRESS', FINISHED: 'FINISHED' };
  const Quest = { values: () => Object.keys(QUESTS).map((k) => Quest[k]) };
  for (const [key, [name, com]] of Object.entries(QUESTS)) {
    Quest[key] = {
      name: () => key,
      getName: () => name,
      getId: () => com,
      toString: () => key,
      getState(client) {
        const w = client.getWidget(274, com);
        const rgb = w ? w.getTextColor() : 0xff0000;
        const r = (rgb >> 16) & 0xff; const g = (rgb >> 8) & 0xff;
        if (g >= 0x80 && r < 0x80) return QuestState.FINISHED;
        if (g >= 0x80 && r >= 0x80) return QuestState.IN_PROGRESS;
        return QuestState.NOT_STARTED;
      },
    };
  }
  rl.Quest = Quest;
  rl.QuestState = QuestState;
  rl.VarPlayerID = Object.assign(rl.VarPlayerID || {}, { QP: 101 });
})();
""" % json.dumps(quests, separators=(',', ':'))
    open(OUT, 'w').write(js)
    print(len(quests), 'quests ->', os.path.relpath(OUT, REPO))


if __name__ == '__main__':
    main()
