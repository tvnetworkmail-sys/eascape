"""RuneLite's ItemManager.getItemStats (item_stats.json) for the 2007 items, from our server's obj configs.

    python3 itemstats.py [client_items.json]

writes app/src/plugins/runelite/itemstats.js. RuneLite's stats are OSRS's; the 2007 bonuses are the server's
`param=<bonus>,N` lines (content/scripts/**/*.obj: the unpacked all.obj first, the hand-edited configs over it),
with `wearpos` for the slot and `weight` for the weight. Only wearable items (a wearpos) are kept. Attack speed is the
`attackrate` param, as the server's combat scripts read it (oc_param), with the param's default 4 (combat.param) for a
weapon without one. Keys are the client's item ids (see client_id).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gameval  # noqa: E402

OUT = os.path.join(gameval.REPO, 'app/src/plugins/runelite/itemstats.js')
# ItemEquipmentStats' field order
FIELDS = ['stabattack', 'slashattack', 'crushattack', 'magicattack', 'rangeattack', 'stabdefence', 'slashdefence',
          'crushdefence', 'magicdefence', 'rangedefence', 'strengthbonus', 'rangebonus', 'prayerbonus', 'attackrate']
# OSRS EquipmentInventorySlot ids
SLOTS = {'hat': 0, 'back': 1, 'front': 2, 'righthand': 3, 'torso': 4, 'lefthand': 5, 'legs': 7, 'hands': 9,
         'feet': 10, 'ring': 12, 'quiver': 13}


CLIENT = {}


def client_id(key, debug, display):
    """The running client's id for pack key `key`: the pack keys aren't the client's ids for renumbered items, whose
    debug names end in their client (OSRS) id (wood_camo_top_10053 is pack key 9185 but client id 10053). With
    client_items.json ({id: name}) the id whose client name is the obj's display name wins; without it, the key."""
    if not CLIENT:
        return key
    m = re.search(r'_(\d+)$', debug)
    cands = [key] + ([int(m.group(1))] if m and int(m.group(1)) != key else [])
    for c in cands:
        if display and CLIENT.get(str(c)) == display:
            return c
    return None


def main():
    names = {v: k for k, v in gameval.pack('ItemID').items()}
    root = os.path.join(gameval.REPO, 'content/scripts')
    files = []
    for d, _, fs in os.walk(root):
        files += [os.path.join(d, f) for f in fs if f.endswith('.obj')]
    files.sort(key=lambda p: ('_unpack' not in p, p))
    objs = {}
    for p in files:
        cur = None
        for line in open(p, encoding='utf-8', errors='replace'):
            line = line.strip()
            if line.startswith('['):
                cur = objs.setdefault(line[1:-1], {})
            elif cur is not None and '=' in line:
                k, _, v = line.partition('=')
                if k == 'param':
                    pk, _, pv = v.partition(',')
                    cur[pk] = pv
                elif k in ('wearpos', 'weight', 'wearpos2', 'name'):
                    cur[k] = v
    out = {}
    for name, o in objs.items():
        if name not in names or 'wearpos' not in o:
            continue
        vals = []
        for f in FIELDS:
            # (attackrate: the param's default is 4, combat.param; RuneLite's aspeed is only set for weapons)
            dflt = '4' if f == 'attackrate' and o['wearpos'] == 'righthand' else '0'
            try:
                vals.append(int(o.get(f, dflt)))
            except ValueError:
                vals.append(0)
        w = o.get('weight', '0')
        m = re.match(r'^(-?[\d.]+)(kg|g)?$', w)
        weight = 0.0
        if m:
            weight = float(m.group(1)) / (1000 if m.group(2) == 'g' else 1)
        two = o.get('wearpos2') == 'lefthand'
        cid = client_id(names[name], name, o.get('name'))
        if cid is None:
            continue
        out[cid] = [SLOTS.get(o['wearpos'], -1), 1 if two else 0, round(weight, 3)] + vals
    body = json.dumps({str(k): out[k] for k in sorted(out)}, separators=(',', ':'))
    with open(OUT, 'w') as f:
        f.write("'use strict';\n// Generated by app/tools/runelite/itemstats.py from the server's obj configs: id -> [slot, two-handed, weight,\n"
                "// " + ', '.join(FIELDS) + "].\n")
        f.write("// Read by the core's ItemManager.getItemStats (core2007.js).\n(() => {\n  const ll = window.__lostlite;\n  const rl = ll && ll.rl;\n  if (!rl) return;\n")
        f.write('  rl.ITEM_STATS_2007 = ' + body + ';\n})();\n')
    print(len(out), 'items')


if __name__ == '__main__':
    if len(sys.argv) > 1:
        CLIENT.update(json.load(open(sys.argv[1])))
    main()
