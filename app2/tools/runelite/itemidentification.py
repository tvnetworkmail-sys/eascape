"""RuneLite's ItemIdentification enum trimmed to the 2007 cache.

    RUNELITE_SRC=<RuneLite source root> python3 itemidentification.py <client_items.json>

writes app/src/plugins/itemidentification/data.js: [NAME, Type, medName, shortName, [ids]] for each constant with at
least one item in the 2007 cache. The game client's item ids are OSRS's (8007 is the Varrock teleport tablet); the
names come from client_items.json, a dump of the running client's item definitions ({id: name}, from
rl.client.getItemDefinition(i).getName() for every id). An id is kept when the client has an item there.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gameval  # noqa: E402

OUT = os.path.join(gameval.REPO, 'app/src/plugins/itemidentification/data.js')
SRC = 'runelite-client/src/main/java/net/runelite/client/plugins/itemidentification/ItemIdentification.java'


def words(s):
    return set(w for w in re.findall(r'[a-z]+', s.lower()) if len(w) > 2)


NAMES = {}


def item_ok(gv_name, i):
    return str(i) in NAMES


def main():
    text = open(os.path.join(gameval.RL, SRC)).read()
    out = []
    dropped = []
    for name, args, _ in gameval.enum_entries(text, 'ItemIdentification'):
        if len(args) < 4 or not args[0].startswith('Type.'):
            continue
        typ = args[0][5:]
        med = args[1].strip('"')
        short = args[2].strip('"')
        ids = []
        for a in args[3:]:
            m = re.match(r'ItemID\.(\w+)', a.strip())
            if not m:
                continue
            i = gameval.gameval('ItemID').get(m.group(1))
            if i is not None and item_ok(m.group(1), i):
                ids.append(i)
        if ids:
            out.append([name, typ, med, short, ids])
        else:
            dropped.append(name)
    js = ('// Generated by app/tools/runelite/itemidentification.py: RuneLite\'s ItemIdentification enum trimmed to the items in\n'
          '// the 2007 cache: [NAME, Type, medName, shortName, [2007 item ids]].\n'
          'window.__lostlite && (window.__lostlite.itemIdentificationData = ' + json.dumps(out, separators=(',', ':')) + ');\n')
    open(OUT, 'w').write(js)
    print(len(out), 'kept,', len(dropped), 'dropped:', ' '.join(dropped))


if __name__ == '__main__':
    NAMES.update(json.load(open(sys.argv[1])))
    main()
