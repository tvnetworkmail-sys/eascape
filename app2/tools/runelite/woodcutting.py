"""Woodcutting clone data from RuneLite's source, trimmed to the 2007 cache.

    RUNELITE_SRC=<RuneLite checkout> python3 woodcutting.py

writes app/src/plugins/woodcutting/trees.js: WoodcuttingPlugin.WOODCUTTING_ANIMS (each gameval name resolved against
the 2007 cache) and the tree respawns.

RuneLite takes a felled tree's respawn time from ADD_OVERLAYTIMER_LOC (Jagex's server, since 2023). The 2007 server
sends no such timer, so the respawns come from the data the server uses: each tree (content/scripts/skill_woodcutting/
configs/trees.dbrow) with its respawn ticks and the stump it turns into (its next_loc_stage param in all.loc). A
respawnrate of 0 (normal, burnt and achey trees) is 120 + random(80) ticks on the server: the timer takes the longest,
199 ticks, and ends when the stump turns back into a tree.
"""
import json
import os
import re

import gameval as gv

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.normpath(os.path.join(HERE, '..', '..'))
CONTENT = os.path.join(gv.REPO, 'content')
JAVA = os.path.join(gv.RL, 'runelite-client/src/main/java/net/runelite/client/plugins/woodcutting/WoodcuttingPlugin.java')
RANDOM_MAX = 120 + 80 - 1


def anims():
    body = open(JAVA).read().split('WOODCUTTING_ANIMS = ', 1)[1].split(';', 1)[0]
    out = []
    for n in re.findall(r'AnimationID\.(\w+)', body):
        i = gv.resolve('AnimationID', n)
        if i is not None and i not in out:
            out.append(i)
    return out



def trees():
    by_name = {}
    for i, n in gv.pack('ObjectID').items():
        by_name.setdefault(n, i)
    nxt = gv.loc_params('next_loc_stage')
    respawns, stumps = {}, set()
    for block in open(os.path.join(CONTENT, 'scripts/skill_woodcutting/configs/trees.dbrow')).read().split('\n['):
        names = re.findall(r'^data=tree,(\w+)', block, re.M)
        rate = re.search(r'^data=respawnrate,(\d+)', block, re.M)
        if not rate:
            continue
        ticks = int(rate.group(1)) or RANDOM_MAX
        for n in names:
            if n in by_name and n in nxt and nxt[n] in by_name:
                respawns[by_name[n]] = [by_name[nxt[n]], ticks]
                stumps.add(by_name[nxt[n]])
    return respawns, sorted(stumps)


def main():
    a = anims()
    respawns, stumps = trees()
    data = {'WOODCUTTING_ANIMS': a, 'TREE_RESPAWNS': {str(k): v for k, v in sorted(respawns.items())}, 'STUMPS': stumps}
    with open(os.path.join(APP, 'src/plugins/woodcutting/trees.js'), 'w') as f:
        f.write("'use strict';\n// generated by app/tools/runelite/woodcutting.py: WOODCUTTING_ANIMS in the 2007 cache, and each tree's\n"
                "// [stump, respawn ticks] from the server's woodcutting data (RuneLite reads these from ADD_OVERLAYTIMER_LOC)\n"
                "(() => {\n  const ll = window.__lostlite;\n  if (!ll) return;\n  ll.woodcuttingTrees = " + json.dumps(data, separators=(',', ':')) + ";\n})();\n")
    print('animations', a, 'trees', len(respawns), 'stumps', len(stumps))


if __name__ == '__main__':
    main()
