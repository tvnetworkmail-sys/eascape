"""RuneLite's ItemStatChanges table (Item Stats) trimmed to the 2007 cache.

    RUNELITE_SRC=<RuneLite source root> python3 itemstatchanges.py <client_items.json>

writes app/src/plugins/itemstats/changes.js: ItemStatChanges.init() translated to JS, one add(effect, ids) per Java
add() with the ids the running client has (client_items.json: {id: name}; the client's item ids are OSRS's). An add()
with no item left in the 2007 cache is dropped, and so are the locals only those used.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gameval  # noqa: E402

OUT = os.path.join(gameval.REPO, 'app/src/plugins/itemstats/changes.js')
SRC = 'runelite-client/src/main/java/net/runelite/client/plugins/itemstats/ItemStatChanges.java'
NAMES = {}
# from 11678 up the 2007 cache's items are its own (God Wars, Varrock armour, ...: OSRS gave them new ids and reused
# these for later items such as Nightmare Zone's potions), so an OSRS id there isn't the same item
OSRS_RENUMBERED = 11678


def statements(body):
    out, depth, cur = [], 0, ''
    for ch in body:
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
        if ch == ';' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    return [s for s in out if s]


def js_expr(e):
    e = re.sub(r'\(int\)\s*\(', 'Math.trunc(', e)
    e = re.sub(r'\(int\)\s*Math\.ceil\(([^()]*)\)', r'Math.trunc(Math.ceil(\1))', e)
    assert '(int)' not in e, e
    e = re.sub(r'\b(\w+)\s*->', r'(\1) =>', e)
    e = re.sub(r'(\d)\.(\d+)?f\b', lambda m: m.group(0)[:-1], e)
    e = re.sub(r'\bnew (\w+)\(', r'new \1(', e)
    return re.sub(r'\s+', ' ', e)


def main():
    text = open(os.path.join(gameval.RL, SRC)).read()
    text = re.sub(r'//[^\n]*', '', text)
    body = text[text.index('private void init()'):]
    body = body[body.index('{') + 1:]
    body = body[:body.index('log.debug(')]
    stmts = statements(body)
    ids = gameval.gameval('ItemID')
    locals_, adds, dropped = {}, [], 0
    for s in stmts:
        m = re.match(r'(?:final\s+)?(\w+)\s+(\w+)\s*=\s*(.*)$', s, re.S)
        if m and not s.startswith('add('):
            locals_[m.group(2)] = js_expr(m.group(3))
            continue
        assert s.startswith('add('), s
        args = gameval.split_top(s[4:-1])
        keep = []
        for a in args[1:]:
            mm = re.match(r'ItemID\.(\w+)$', a.strip())
            assert mm, a
            i = ids.get(mm.group(1))
            if i is not None and str(i) in NAMES and i < OSRS_RENUMBERED:
                keep.append(i)
        if keep:
            adds.append((js_expr(args[0]), keep))
        else:
            dropped += 1
    used = set()
    def need(expr):
        for name, val in locals_.items():
            if name not in used and re.search(r'\b%s\b' % name, expr):
                used.add(name)
                need(val)
    for e, _ in adds:
        need(e)
    lines = ['// Generated by app/tools/runelite/itemstatchanges.py: RuneLite\'s ItemStatChanges.init() with the items in the',
             '// 2007 cache (an add() with none of its items in the cache is left out). Item Stats\' page.js runs it.',
             'window.__lostlite && (window.__lostlite.itemStatChangesInit = (B, add) => {',
             '  const { food, combo, boost, heal, dec, perc, range, ATTACK_POT, STRENGTH_POT, DEFENCE_POT, SUPER_ATTACK_POT, SUPER_STRENGTH_POT, SUPER_DEFENCE_POT } = B;',
             '  const { ' + ', '.join(sorted(set(re.findall(r'\b[A-Z][A-Z_]+[A-Z]\b', ' '.join(e for e, _ in adds) + ' '.join(locals_[u] for u in used))) - {'ATTACK_POT', 'STRENGTH_POT', 'DEFENCE_POT', 'SUPER_ATTACK_POT', 'SUPER_STRENGTH_POT', 'SUPER_DEFENCE_POT'})) + ' } = B.Stats;']
    classes = sorted(set(re.findall(r'new (\w+)\(', ' '.join(e for e, _ in adds) + ' '.join(locals_[u] for u in used))))
    lines.append('  const { ' + ', '.join(classes) + ' } = B;')
    for name in locals_:
        if name in used:
            lines.append('  const %s = %s;' % (name, locals_[name]))
    for e, keep in adds:
        lines.append('  add(%s, %s);' % (e, ', '.join(map(str, keep))))
    lines.append('});')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(len(adds), 'adds kept,', dropped, 'dropped; classes:', classes)


if __name__ == '__main__':
    NAMES.update(json.load(open(sys.argv[1])))
    main()
