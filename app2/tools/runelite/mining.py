"""Mining clone data from RuneLite's source, trimmed to the 2007 cache.

    RUNELITE_SRC=<RuneLite checkout> python3 mining.py

writes app/src/plugins/mining/rocks.js: MiningAnimation's sets (each gameval name resolved against the 2007 cache;
the wall / power-swing / later pickaxes have no 2007 animation) and the rock respawns.

RuneLite takes a depleted rock's respawn time from ADD_OVERLAYTIMER_LOC, a script Jagex's server calls since 2023. The
2007 server sends no such timer, so the respawns come from the same data the server uses: each mineable rock (the
server's mining_table rows in content/scripts/skill_mining/configs/mine.dbrow) with its base respawn ticks and the
depleted loc it turns into (its next_loc_stage_mining param in all.loc). The server scales the ticks by the world's
player count (scale_by_playercount: base * (4000 - players) / 4000), so on a quiet world they are the base ticks.
"""
import json
import os
import re

import gameval as gv

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.normpath(os.path.join(HERE, '..', '..'))
CONTENT = os.path.join(gv.REPO, 'content')
JAVA = os.path.join(gv.RL, 'runelite-client/src/main/java/net/runelite/client/plugins/mining/MiningAnimation.java')


def anim_sets():
    src = open(JAVA).read()
    out = {}
    for name in ('MINING_ANIMATIONS', 'WAll_ANIMATIONS'):
        body = src.split(name, 1)[1].split(';', 1)[0]
        ids = []
        for n in re.findall(r'AnimationID\.(\w+)', body):
            i = gv.resolve('AnimationID', n)
            if i is not None and i not in ids:
                ids.append(i)
        out[name] = ids
    return out


def rocks():
    by_name = {}
    for i, n in gv.pack('ObjectID').items():
        by_name.setdefault(n, i)
    nxt = gv.loc_params('next_loc_stage_mining')  # loc name -> depleted loc name
    respawns, empties = {}, set()
    for block in open(os.path.join(CONTENT, 'scripts/skill_mining/configs/mine.dbrow')).read().split('\n['):
        names = re.findall(r'^data=rock,(\w+)', block, re.M)
        rate = re.search(r'^data=rock_respawnrate,(\d+)', block, re.M)
        if not rate:
            continue  # (rune essence never depletes)
        for n in names:
            if n in by_name and n in nxt and nxt[n] in by_name:
                respawns[by_name[n]] = [by_name[nxt[n]], int(rate.group(1))]
                empties.add(by_name[nxt[n]])
    return respawns, sorted(empties)


def main():
    a = anim_sets()
    respawns, empties = rocks()
    data = {'MINING_ANIMATIONS': a['MINING_ANIMATIONS'], 'WALL_ANIMATIONS': a['WAll_ANIMATIONS'],
            'ROCK_RESPAWNS': {str(k): v for k, v in sorted(respawns.items())}, 'DEPLETED': empties}
    out = os.path.join(APP, 'src/plugins/mining/rocks.js')
    with open(out, 'w') as f:
        f.write("'use strict';\n// generated by app/tools/runelite/mining.py: MiningAnimation's sets in the 2007 cache, and each rock's\n"
                "// [depleted loc, respawn ticks] from the server's mining data (RuneLite reads these from ADD_OVERLAYTIMER_LOC)\n"
                "(() => {\n  const ll = window.__lostlite;\n  if (!ll) return;\n  ll.miningRocks = " + json.dumps(data, separators=(',', ':')) + ";\n})();\n")
    print('animations', len(a['MINING_ANIMATIONS']), 'wall', len(a['WAll_ANIMATIONS']), 'rocks', len(respawns), 'depleted', len(empties))


if __name__ == '__main__':
    main()
