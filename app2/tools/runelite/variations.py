"""RuneLite's net.runelite.client.game.ItemVariationMapping (item_variations.json), trimmed to the 2007 cache.

    RUNELITE_SRC=<RuneLite source root> python3 variations.py

writes app/src/plugins/runelite/itemvariations.js (rl.ItemVariationMapping: map(id), getVariations(id)). Each group
keeps RuneLite's base id (the first one, so tags keep RuneLite's keys and exports) and only the ids that are in the
2007 cache under the group's name; a group with no such id goes.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gameval  # noqa: E402

OUT = os.path.join(gameval.REPO, 'app/src/plugins/runelite/itemvariations.js')


def norm(s):
    return re.sub(r'[^a-z0-9]', '', s.lower())


def main():
    src = json.load(open(os.path.join(gameval.RL, 'runelite-client/src/main/resources/item_variations.json')))
    groups = []
    for name, ids in src.items():
        base = ids[0]
        keep = []
        for i in ids:
            n = gameval.name2007('ItemID', i)
            # the 2007 item with that id is the same item (its display name starts with the group's name)
            if n and n[1] and norm(n[1]).startswith(norm(name)[:6]):
                keep.append(i)
        if keep:
            groups.append([base] + [i for i in keep if i != base])
    js = """// Generated by app/tools/runelite/variations.py: RuneLite's ItemVariationMapping (item_variations.json) trimmed to the
// items in the 2007 cache; each group is [RuneLite's base id, ...the 2007 ids]. rl.ItemVariationMapping.map / getVariations.
(() => {
  const ll = window.__lostlite;
  const rl = ll && ll.rl;
  if (!rl) return;
  const GROUPS = %s;
  const MAPPINGS = new Map();
  const INVERTED = new Map();
  for (const g of GROUPS) {
    const base = g[0];
    const all = [base];
    for (const id of g.slice(1)) { MAPPINGS.set(id, base); all.push(id); }
    INVERTED.set(base, all);
  }
  rl.ItemVariationMapping = {
    map: (itemId) => (MAPPINGS.has(itemId) ? MAPPINGS.get(itemId) : itemId),
    getVariations: (itemId) => INVERTED.get(itemId) || [itemId],
  };
})();
""" % json.dumps(groups, separators=(',', ':'))
    open(OUT, 'w').write(js)
    print(len(groups), 'of', len(src), 'groups ->', os.path.relpath(OUT, gameval.REPO))


if __name__ == '__main__':
    main()
