#!/usr/bin/env python3
# Builds app/src/plugins/slayer/data.js: RuneLite's slayer Task enum trimmed to our server's 2007 tasks.
#   python3 gen.py <runelite-src> <names07.json>
# - tasks: RuneLite's Task entries whose name is one of the server's task names (content/.../task_name.enum)
# - item ids: RuneLite's gameval ItemID constants; an item after the 2007 cache (no such obj) falls back to
#   the enchanted gem (ItemID.SLAYER_GEM, 4155), as Task.getTask's caller does for an unknown task
# - target names: only those that name an NPC in the 2007 cache
# - SlayerTask (the DB table RuneLite reads the varp's task id through): the server's ids and names
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
CONTENT = os.environ.get('CONTENT', os.path.join(os.path.dirname(REPO), 'content'))
rl, names07 = sys.argv[1], sys.argv[2]
N = json.load(open(names07))
objs = {int(k): v for k, v in N['obj'].items()}
npc_names = {str(v).lower() for v in N['npc'].values() if v}

ids = {}
for m in re.finditer(r'public static final int (\w+) = (\d+);', open(os.path.join(rl, 'runelite-api/src/main/java/net/runelite/api/gameval/ItemID.java')).read()):
    ids.setdefault(m.group(1), int(m.group(2)))

src = open(os.path.join(rl, 'runelite-client/src/main/java/net/runelite/client/plugins/slayer/Task.java')).read()
tasks = []
for m in re.finditer(r'^\s*([A-Z_0-9]+)\("([^"]+)", ItemID\.(\w+)((?:, [^)]*)?)\)[,;]', src, re.M):
    key, name, item, rest = m.groups()
    args = [a.strip() for a in rest.split(',') if a.strip()] if rest else []
    thr, weak = -1, -1
    if args and re.fullmatch(r'\d+', args[0]):
        thr, weak = int(args[0]), ids[args[1].split('.')[1]]
        args = args[2:]
    targets = [a.strip('"') for a in args]
    tasks.append({'key': key, 'name': name, 'item': ids[item], 'thr': thr, 'weak': weak, 'targets': targets})

const = dict(re.findall(r'\^(slayer_\w+) = (\d+)', open(os.path.join(CONTENT, 'scripts/skill_slayer/configs/slayer.constant')).read()))
server = {int(const[k]): v for k, v in re.findall(r'val=\^(slayer_\w+),(.+)', open(os.path.join(CONTENT, 'scripts/skill_slayer/configs/task_name.enum')).read())}

# the server's spellings of a few names, as OSRS (and so RuneLite) spells them (the ids are OSRS's)
ALIAS = {'Moss Giant': 'Moss giants', 'Vampires': 'Vampyres', 'Aberrant Specters': 'Aberrant spectres', 'Kalphite': 'Kalphites',
         'Cave Slime': 'Cave slimes'}
server = {k: ALIAS.get(v.strip(), v.strip()) for k, v in server.items()}
by_name = {t['name'].lower(): t for t in tasks}
out, missing = [], []
for tid, sname in sorted(server.items()):
    t = by_name.get(sname.lower())
    if not t:
        missing.append(sname); continue
    item = t['item'] if t['item'] in objs else 4155
    weak = t['weak'] if t['weak'] in objs else -1
    out.append({'key': t['key'], 'name': t['name'], 'itemSpriteId': item, 'weaknessThreshold': t['thr'] if weak >= 0 else -1,
                'weaknessItem': weak, 'targetNames': [n for n in t['targets'] if n.lower() in npc_names]})
db = [{'id': tid, 'name': sname} for tid, sname in sorted(server.items())]
with open(os.path.join(REPO, 'src/plugins/slayer/data.js'), 'w') as f:
    f.write('// Generated by app/tools/slayer/gen.py: RuneLite\'s slayer Task enum trimmed to our server\'s 2007 tasks,\n')
    f.write('// and the SlayerTask table (the server\'s task ids, varp 395, with their names).\n')
    f.write('window.__lostlite && (window.__lostlite.slayerData = ' + json.dumps({'tasks': out, 'slayerTask': db}, separators=(',', ':')) + ');\n')
print(len(out), 'tasks;', 'server names with no RuneLite task:', missing)
